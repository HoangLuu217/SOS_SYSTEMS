function buildSheetFormHeader(
  title: string,
  subtitle: string,
  colCount: number,
  metaPairs: [string, string | number, string, string | number][]
): { rows: RowSpec[]; merges: string[]; nextRow1: number } {
  const rows: RowSpec[] = [];
  const merges: string[] = [];
  const lastCol = colLetter(colCount - 1);

  const r1: (CellSpec | null)[] = Array.from({ length: colCount }, (_, i) =>
    i === 0 ? { v: title, s: 1 } : { v: '', s: 1 }
  );
  rows.push({ height: 32, cells: r1 });
  merges.push(`A1:${lastCol}1`);

  const r2: (CellSpec | null)[] = Array.from({ length: colCount }, (_, i) =>
    i === 0 ? { v: subtitle, s: 2 } : { v: '', s: 2 }
  );
  rows.push({ height: 22, cells: r2 });
  merges.push(`A2:${lastCol}2`);

  rows.push({ height: 10, cells: [] });

  const r4: (CellSpec | null)[] = Array.from({ length: colCount }, (_, i) =>
    i === 0 ? { v: 'I. THÔNG TIN BIỂU MẪU & TỔNG HỢP CHỈ SỐ', s: 6 } : { v: '', s: 6 }
  );
  rows.push({ height: 24, cells: r4 });
  merges.push(`A4:${lastCol}4`);

  let currentRow1 = 5;
  for (const [k1, v1, k2, v2] of metaPairs) {
    const cells: (CellSpec | null)[] = Array.from({ length: colCount }, () => ({ v: '', s: 4 }));
    cells[0] = { v: k1, s: 3 };
    cells[1] = {
      v: v1,
      s: typeof v1 === 'number' ? 5 : 4,
      t: typeof v1 === 'number' ? 'n' : 's',
    };
    if (colCount >= 4) {
      cells[2] = { v: k2, s: 3 };
      cells[3] = {
        v: v2,
        s: typeof v2 === 'number' ? 5 : 4,
        t: typeof v2 === 'number' ? 'n' : 's',
      };
      if (colCount > 4) {
        merges.push(`D${currentRow1}:${lastCol}${currentRow1}`);
      }
    }
    rows.push({ height: 21, cells });
    currentRow1 += 1;
  }

  rows.push({ height: 12, cells: [] });
  currentRow1 += 1;

  const rSec2: (CellSpec | null)[] = Array.from({ length: colCount }, (_, i) =>
    i === 0 ? { v: 'II. BẢNG DỮ LIỆU CHI TIẾT', s: 6 } : { v: '', s: 6 }
  );
  rows.push({ height: 24, cells: rSec2 });
  merges.push(`A${currentRow1}:${lastCol}${currentRow1}`);
  currentRow1 += 1;

  return { rows, merges, nextRow1: currentRow1 };
}

function appendDataTable(
  sheetRows: RowSpec[],
  headers: string[],
  dataMatrix: { v: string | number; align?: 'left' | 'center' | 'right' }[][],
  footerCells?: (string | number)[]
) {
  sheetRows.push({
    height: 27,
    cells: headers.map((h) => ({ v: h, s: 7 })),
  });

  if (dataMatrix.length === 0) {
    sheetRows.push({
      height: 24,
      cells: headers.map((_, idx) => ({
        v: idx === 0 ? 'Chưa có bản ghi chi tiết' : '—',
        s: 9,
      })),
    });
    return;
  }

  dataMatrix.forEach((row, rIdx) => {
    const isAlt = rIdx % 2 === 1;
    sheetRows.push({
      height: 21,
      cells: row.map((cell) => {
        const isNum = typeof cell.v === 'number';
        const align = cell.align || (isNum ? 'right' : 'left');
        let styleId: StyleId;
        if (align === 'center') styleId = isAlt ? 12 : 9;
        else if (align === 'right') styleId = isAlt ? 13 : 10;
        else styleId = isAlt ? 11 : 8;
        return {
          v: cell.v,
          s: styleId,
          t: isNum ? 'n' : 's',
        };
      }),
    });
  });

  if (footerCells && footerCells.length > 0) {
    sheetRows.push({
      height: 24,
      cells: footerCells.map((fc) => ({
        v: fc,
        s: typeof fc === 'number' ? 15 : 14,
        t: typeof fc === 'number' ? 'n' : 's',
      })),
    });
  }
}

